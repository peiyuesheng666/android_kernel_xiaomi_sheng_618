#!/usr/bin/env python3
"""Use checked, same-version platform HIDL interfaces instead of duplicate blobs."""
import json
from pathlib import Path
import re

WORK = Path(__file__).resolve().parents[1]
ROM = Path('/root/sheng-lineage/lineage-24.0')
inventory = WORK / 'device/xiaomi/sheng/proprietary-files.txt'
lines = inventory.read_text().splitlines()
providers = {}
for relative in (ROM / 'out/.module_paths/Android.bp.list').read_text().splitlines():
    if not relative.startswith(('hardware/', 'frameworks/', 'system/libhidl/', 'vendor/qcom/opensource/')):
        continue
    file = ROM / relative
    if not file.is_file():
        continue
    for block in re.findall(r'\bhidl_interface\s*\{(.*?)\n\}', file.read_text(), re.S):
        name = re.search(r'\bname\s*:\s*"([^"]+)"', block)
        if name:
            providers.setdefault(name[1], []).append(relative)
# These explicitly suffixed bindings are a separate stock interface ABI.
renamed_bindings = {'vendor.qti.hardware.qccsyshal@1.0', 'vendor.qti.hardware.qccsyshal@1.1',
                    'vendor.qti.hardware.qccsyshal@1.2', 'vendor.qti.hardware.qccvndhal@1.0',
                    'vendor.qti.imsrtpservice@3.0', 'vendor.qti.imsrtpservice@3.1', 'vendor.qti.diaghal@1.0'}
removed = []
kept = []
for line in lines:
    match = re.fullmatch(r'(?:vendor|odm|system_ext)/lib(?:64)?/([^/@]+)@([0-9.]+)\.so', line)
    if not match:
        kept.append(line)
        continue
    name, version = match.groups()
    module = name + '@' + version
    matches = providers.get(module, [])
    if module in renamed_bindings or len(matches) != 1:
        kept.append(line)
        continue
    relative = Path(matches[0])
    source = ROM / relative
    assert source.is_file(), f'No source for {line}: {source}'
    text = source.read_text()
    assert 'hidl_interface' in text and re.search(r'\bname\s*:\s*"' + re.escape(module) + '"', text), module
    removed.append({'blob': line, 'module': module, 'source': str(relative)})
inventory.write_text('\n'.join(kept) + '\n')
report_path = WORK / 'reports/source-hidl-interfaces.json'
previous = json.loads(report_path.read_text())['removed_duplicates'] if report_path.exists() else []
report_path.write_text(json.dumps({'removed_duplicates': previous + removed,
    'reason': 'Same-version HIDL bindings are generated by platform source; driver implementations remain stock'}, indent=2) + '\n')
print(f'Removed {len(removed)} duplicate interface libraries after verifying every source module')
